"""Описание блок-схем для контрольной точки (координаты в мм внутри рисунка)."""
from ooxml import shape, line, polyline, label, figure_paragraph


def flow_general():
    """Рисунок 2.1 — общая содержательная блок-схема программы."""
    cx = 60
    c = []
    def box(kind, text, y, h, w=70):
        c.append(shape(kind, text, cx - w / 2, y, w, h))
    box('terminator', 'Начало', 0, 9, 40)
    box('io', 'Ввод исходных данных:\nf(x), a, b, метод, n, ε', 13, 14, 70)
    box('decision', 'Данные\nкорректны?', 31, 20, 56)
    box('subprocess', 'Разбор формулы\nв дерево выражения', 56, 12)
    box('process', 'Выбор метода: трапеций,\nСимпсона или оба', 73, 12)
    box('subprocess', 'Вычисление интеграла\nвыбранным методом', 90, 14)
    box('decision', 'f(x) вычисляется\nбез ошибок?', 109, 20, 62)
    box('io', 'Вывод результатов на форму', 134, 14, 70)
    box('decision', 'Сохранить\nв HTML?', 153, 20, 56)
    box('subprocess', 'Формирование и запись\nHTML-отчёта', 178, 12)
    box('terminator', 'Конец', 195, 9, 40)
    # основная ветка
    for y1, y2 in [(9, 13), (27, 31), (51, 56), (68, 73), (85, 90), (104, 109), (129, 134), (148, 153), (173, 178), (190, 195)]:
        c.append(line(cx, y1, cx, y2, arrow=True))
    # блок ошибки и его связи
    c.append(shape('process', 'Сообщение об ошибке\nв строке состояния', 105, 35, 60, 12))
    c.append(polyline([(88, 41), (105, 41)]))
    c.append(polyline([(91, 119), (135, 119), (135, 47)]))
    c.append(polyline([(135, 35), (135, 20), (102, 20)]))
    # выход «Нет» при «Сохранить в HTML?»
    c.append(polyline([(88, 163), (150, 163), (150, 199.5), (80, 199.5)]))
    # подписи
    c += [label('Нет', 90, 36.5, 9), label('Да', 61.5, 51, 8),
          label('Нет', 92, 114.5, 9), label('Да', 61.5, 129, 8),
          label('Нет', 90, 158.5, 9), label('Да', 61.5, 173, 8)]
    return figure_paragraph(172, 205, c, 'Рисунок 2.1')


def flow_integrate():
    """Рисунок 2.2 — алгоритм вычисления интеграла (Integrator.Integrate)."""
    cx = 55
    c = []
    def box(kind, text, y, h, w=80):
        c.append(shape(kind, text, cx - w / 2, y, w, h))
    box('terminator', 'Начало', 0, 8, 40)
    box('io', 'Ввод: f(x), a, b, метод, n, ε', 12, 12)
    box('process', 'Проверка параметров;\nдля метода Симпсона n делается чётным', 28, 12)
    box('process', 'I := Q(n)', 44, 12, 60)
    box('decision', 'ε = 0 ?', 60, 16, 50)
    box('process', 'n₂ := 2n;  I₂ := Q(n₂)\nR := |I₂ − I| / (2ᵖ − 1)', 80, 14)
    box('decision', 'R ≤ ε  или\n2n > 2²⁰ ?', 98, 18, 64)
    box('io', 'Вывод: I, n, h, R, число\nвычислений, время, таблица', 122, 14, 90)
    box('terminator', 'Конец', 140, 8, 40)
    for y1, y2 in [(8, 12), (24, 28), (40, 44), (56, 60), (76, 80), (94, 98), (116, 122), (136, 140)]:
        c.append(line(cx, y1, cx, y2, arrow=True))
    # ветка ε = 0: оценка погрешности по Рунге
    c.append(shape('process', 'R := |Q(2n) − I| / (2ᵖ − 1)\n(оценка погрешности)', 105, 60, 65, 16))
    c.append(polyline([(80, 68), (105, 68)]))
    c.append(polyline([(170, 68), (174, 68), (174, 129), (100, 129)]))
    # ветка «Нет» после проверки R ≤ ε: удвоение продолжается
    c.append(shape('process', 'I := I₂;  n := n₂', 105, 103, 65, 8))
    c.append(polyline([(87, 107), (105, 107)]))
    c.append(polyline([(137.5, 103), (137.5, 87), (95, 87)]))
    c += [label('Да', 82, 63.5, 8), label('Нет', 56.5, 76, 9),
          label('Нет', 88, 102.5, 9), label('Да', 56.5, 115, 8)]
    return figure_paragraph(176, 148, c, 'Рисунок 2.2')
